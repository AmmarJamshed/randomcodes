class AdaptiveLearningService:
    """
    Adjust rule confidence from analyst feedback.
    Never deletes rules. No neural models.
    """

    STEP_CONFIRM = 0.04
    STEP_REJECT = 0.05
    STEP_USEFUL = 0.02
    STEP_IRRELEVANT = 0.03

    def record_feedback(
        self,
        rule_id: str,
        feedback_type: str,
        *,
        case_id: int | None = None,
        user_id: int | None = None,
        username: str = "",
        comment: str = "",
    ) -> float:
        feedback_type = feedback_type.strip().lower().replace(" ", "_")
        with session_scope() as session:
            rc = session.query(RuleConfidence).filter_by(rule_id=rule_id).first()
            if not rc:
                rc = RuleConfidence(rule_id=rule_id, confidence=0.5)
                session.add(rc)
                session.flush()

            if feedback_type in {"correct", "true_positive", "confirmed"}:
                rc.confirm_count = (rc.confirm_count or 0) + 1
                rc.confidence = min(0.95, (rc.confidence or 0.5) + self.STEP_CONFIRM)
            elif feedback_type in {"false_positive", "rejected"}:
                rc.reject_count = (rc.reject_count or 0) + 1
                rc.confidence = max(0.05, (rc.confidence or 0.5) - self.STEP_REJECT)
            elif feedback_type in {"useful"}:
                rc.useful_count = (rc.useful_count or 0) + 1
                rc.confidence = min(0.95, (rc.confidence or 0.5) + self.STEP_USEFUL)
            elif feedback_type in {"irrelevant"}:
                rc.irrelevant_count = (rc.irrelevant_count or 0) + 1
                rc.confidence = max(0.05, (rc.confidence or 0.5) - self.STEP_IRRELEVANT)
            elif feedback_type in {"false_negative"}:
                # Missed indicator — boost slightly so rule is not under-weighted
                rc.confirm_count = (rc.confirm_count or 0) + 1
                rc.confidence = min(0.95, (rc.confidence or 0.5) + self.STEP_CONFIRM)

            new_conf = float(rc.confidence)

            session.add(
                AnalystFeedback(
                    rule_id=rule_id,
                    case_id=case_id,
                    feedback_type=feedback_type,
                    comment=comment,
                    user_id=user_id,
                )
            )

        # Mirror into Excel knowledge base feedback sheet
        try:
            kb = get_knowledge_base()
            kb.record_feedback_row(
                {
                    "Timestamp": utc_now_iso(),
                    "Rule ID": rule_id,
                    "Feedback": feedback_type,
                    "Case ID": case_id or "",
                    "Analyst": username,
                    "Comment": comment,
                }
            )
        except Exception as exc:  # noqa: BLE001
            logger.warning("KB feedback mirror failed: %s", exc)

        audit(
            "analyst_feedback",
            user_id=user_id,
            username=username,
            entity_type="rule",
            entity_id=rule_id,
            details=f"{feedback_type}: {comment}",
        )
        return new_conf

    def recommend_similar_cases(self, case_id: int) -> list[dict[str, Any]]:
        """Return similar prior cases for analyst recommendation panels."""
        with session_scope() as session:
            current = (
                session.query(InvoiceMemory)
                .filter_by(case_id=case_id)
                .order_by(InvoiceMemory.id.desc())
                .first()
            )
            if not current:
                return []
            extracted = ExtractedTradeData(
                exporter=current.exporter or "",
                importer=current.importer or "",
                invoice_number=current.invoice_number or "",
                total_amount=current.amount,
                currency=current.currency or "",
                hs_code=current.hs_code or "",
                description=current.goods or "",
                country_origin=current.country_origin or "",
                port_of_loading=current.port_origin or "",
                port_of_discharge=current.port_dest or "",
                container=current.container or "",
                bank=current.bank or "",
            )
        mem = MemoryService()
        ctx = mem.build_historical_context(extracted)
        return ctx.get("recommendations", [])



