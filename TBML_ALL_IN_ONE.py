class RuleEngine:
    """
    Weighted boolean / regex / fuzzy / cross-field / historical rule engine.
    No ML. No LLM. Fully explainable.
    """

    def __init__(self) -> None:
        self.cfg = get_config()
        self.kb = get_knowledge_base()
        self.fuzzy_threshold = float(self.cfg.get("rule_engine.fuzzy_threshold", 80))
        self.min_confidence = float(self.cfg.get("rule_engine.min_confidence", 0.3))
        self.chain_boost = float(self.cfg.get("rule_engine.chain_boost", 1.15))

    def investigate(self, ctx: InvestigationContext) -> list[RuleHit]:
        self.kb.reload()
        hits: list[RuleHit] = []
        rules = self.kb.active_rules()

        for rule in rules:
            hit = self._evaluate_rule(rule, ctx)
            if hit and hit.confidence >= self.min_confidence:
                hits.append(hit)

        # Specialized detectors (still driven by rule IDs from KB)
        hits.extend(self._run_specialized_detectors(ctx, {h.rule_id for h in hits}))

        # Reality research can add or replace weaker keyword-only hits for the same rule
        reality_hits = self._reality_research_hits(ctx)
        if reality_hits:
            by_id = {h.rule_id: h for h in hits}
            for rh in reality_hits:
                existing = by_id.get(rh.rule_id)
                if existing is None or rh.confidence >= existing.confidence:
                    by_id[rh.rule_id] = rh
            hits = list(by_id.values())

        # Rule chaining — boost related categories that co-trigger
        hits = self._apply_chaining(hits)

        hits.sort(key=lambda h: (h.adjusted_weight * h.confidence), reverse=True)
        logger.info("Rule engine triggered %d rules", len(hits))
        return hits

    def _evaluate_rule(self, rule: dict[str, Any], ctx: InvestigationContext) -> RuleHit | None:
        rule_id = str(rule.get("Rule ID", "")).strip()
        if not rule_id:
            return None

        keywords = [
            k.strip()
            for k in str(rule.get("Keywords", "")).split(",")
            if k.strip()
        ]
        pattern = str(rule.get("Evidence Pattern", "") or "").strip()
        text = ctx.text or ""
        lower = text.lower()

        matched_snippets: list[str] = []
        score = 0.0
        reasons: list[str] = []

        # Keyword matching
        for kw in keywords:
            if kw.lower() in lower:
                matched_snippets.append(self._snippet(text, kw))
                score += 0.35
                reasons.append(f"Keyword match: '{kw}'")
            else:
                # Fuzzy keyword against sliding windows of text
                ratio = fuzz.partial_ratio(kw.lower(), lower[:5000])
                if ratio >= self.fuzzy_threshold:
                    matched_snippets.append(f"[fuzzy:{ratio}] {kw}")
                    score += 0.25
                    reasons.append(f"Fuzzy keyword match: '{kw}' ({ratio}%)")

        # Regex evidence pattern
        if pattern:
            try:
                for match in re.finditer(pattern, text, re.I | re.M):
                    matched_snippets.append(match.group(0)[:240])
                    score += 0.4
                    reasons.append(f"Pattern match: /{pattern[:60]}/")
                    break
            except re.error as exc:
                logger.warning("Invalid regex for %s: %s", rule_id, exc)

        # Adaptive confidence from analyst feedback
        adaptive = ctx.rule_confidence_map.get(rule_id, 0.5)
        confidence = min(1.0, score * (0.7 + 0.6 * adaptive))

        if confidence < self.min_confidence and not matched_snippets:
            return None
        if not matched_snippets and confidence < 0.5:
            return None

        weight = float(rule.get("Weight", 1) or 1)
        adjusted = weight * (0.5 + adaptive)

        return RuleHit(
            rule_id=rule_id,
            category=str(rule.get("Category", "")),
            description=str(rule.get("Description", "")),
            evidence="; ".join(reasons) if reasons else "Matched knowledge-base criteria",
            matched_text=" | ".join(matched_snippets)[:500],
            confidence=round(confidence, 3),
            weight=weight,
            adjusted_weight=round(adjusted, 3),
            severity=str(rule.get("Severity", "medium")),
            explanation=self._explain(rule, reasons, adaptive),
            suggested_action=str(rule.get("Suggested Action", "")),
            source=str(rule.get("Source", "")),
        )

