def get_project_root() -> Path:
    """
    Writable app root (data, exports, tools, logs).
    When frozen (PyInstaller onedir), this is the folder that contains the .exe.
    """
    if getattr(sys, "frozen", False):
        return Path(sys.executable).resolve().parent
    return Path(__file__).resolve().parent  # onefile: this .py is the app root


def get_bundle_root() -> Path:
    """Read-only bundled resources inside _internal (PyInstaller) or project root."""
    if getattr(sys, "frozen", False) and hasattr(sys, "_MEIPASS"):
        return Path(sys._MEIPASS)
    return get_project_root()


PROJECT_ROOT = get_project_root()
BUNDLE_ROOT = get_bundle_root()


def find_resource(*relative_parts: str) -> Path | None:
    """Find a file/dir beside the exe first, then inside the PyInstaller bundle."""
    for base in (PROJECT_ROOT, BUNDLE_ROOT):
        path = base.joinpath(*relative_parts)
        if path.exists():
            return path
    return None


def materialize_from_bundle(relative: str) -> Path:
    """
    Ensure a bundled asset exists next to the exe (writable / portable).
    Copies from _internal into the exe folder on first run when missing.
    """
    dest = PROJECT_ROOT / relative
    if dest.exists():
        return dest
    src = BUNDLE_ROOT / relative
    if not src.exists():
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    if src.is_dir():
        shutil.copytree(src, dest, dirs_exist_ok=True)
    else:
        shutil.copy2(src, dest)
    return dest


def materialize_runtime_assets() -> None:
    """Copy small bundled assets next to the exe when frozen. tools/ is read from the bundle."""
    if not getattr(sys, "frozen", False):
        return
    for rel in (
        "config/settings.yaml",
        "knowledgebase/TBML_RedFlags.xlsx",
    ):
        try:
            materialize_from_bundle(rel)
        except OSError:
            pass


def _resolve_settings_path() -> Path:
    beside_exe = PROJECT_ROOT / "config" / "settings.yaml"
    if beside_exe.exists():
        return beside_exe
    bundled = BUNDLE_ROOT / "config" / "settings.yaml"
    if bundled.exists():
        return bundled
    return beside_exe


CONFIG_PATH = _resolve_settings_path()


class AppConfig:
    """Central configuration object with typed accessors."""

    def __init__(self, data: dict[str, Any] | None = None) -> None:
        self._data: dict[str, Any] = data or {}
        self._root = PROJECT_ROOT

    @classmethod
    def load(cls, path: Path | None = None) -> "AppConfig":
        cfg_path = path or CONFIG_PATH
        if not cfg_path.exists():
            raise FileNotFoundError(f"Configuration file not found: {cfg_path}")
        with open(cfg_path, "r", encoding="utf-8") as fh:
            data = yaml.safe_load(fh) or {}
        return cls(data)

    def reload(self) -> None:
        self._data = self.load()._data

    def get(self, dotted_key: str, default: Any = None) -> Any:
        node: Any = self._data
        for part in dotted_key.split("."):
            if not isinstance(node, dict) or part not in node:
                return default
            node = node[part]
        return node

    def resolve_path(self, key: str) -> Path:
        """
        Resolve a configured relative path.
        Writable paths stay next to the exe. For missing knowledgebase, prefer
        a bundled copy if present.
        """
        rel = self.get(f"paths.{key}", key)
        path = Path(rel)
        if path.is_absolute():
            path.parent.mkdir(parents=True, exist_ok=True)
            return path

        local = self._root / path
        if key == "knowledgebase" and not local.exists():
            bundled = find_resource(*Path(rel).parts)
            if bundled is not None and bundled.is_file():
                local.parent.mkdir(parents=True, exist_ok=True)
                try:
                    shutil.copy2(bundled, local)
                except OSError:
                    return bundled
        local.parent.mkdir(parents=True, exist_ok=True)
        return local

    @property
    def root(self) -> Path:
        return self._root

    @property
    def app_name(self) -> str:
        return str(self.get("app.name", "TBML Expert"))

    @property
    def version(self) -> str:
        return str(self.get("app.version", "1.0.0"))

    def ensure_directories(self) -> None:
        """Create required runtime directories."""
        for key in (
            "logs",
            "exports",
            "cache_ocr",
            "cache_company",
            "database",
            "knowledgebase",
        ):
            path = self.resolve_path(key)
            if key == "database":
                path.parent.mkdir(parents=True, exist_ok=True)
            elif key == "knowledgebase":
                path.parent.mkdir(parents=True, exist_ok=True)
            else:
                path.mkdir(parents=True, exist_ok=True)
        (self._root / "data").mkdir(parents=True, exist_ok=True)
        (self._root / "tools").mkdir(parents=True, exist_ok=True)
        (self._root / "knowledgebase").mkdir(parents=True, exist_ok=True)


