SEVERITY_SCORE = {
    "low": 25,
    "medium": 50,
    "high": 75,
    "critical": 95,
}


@dataclass
class RiskFactor:
    name: str
    score: float
    weight: float
    explanation: str
    contributing_rules: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class RiskAssessment:
    document_risk: float
    company_risk: float
    country_risk: float
    shipping_risk: float
    financial_risk: float
    historical_similarity: float
    overall_risk: float
    level: str
    factors: list[RiskFactor]
    recommendations: list[str]
    explainability: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "document_risk": self.document_risk,
            "company_risk": self.company_risk,
            "country_risk": self.country_risk,
            "shipping_risk": self.shipping_risk,
            "financial_risk": self.financial_risk,
            "historical_similarity": self.historical_similarity,
            "overall_risk": self.overall_risk,
            "level": self.level,
            "factors": [f.to_dict() for f in self.factors],
            "recommendations": self.recommendations,
            "explainability": self.explainability,
        }


class RiskEngine:
    """
    Transparent weighted risk aggregation.
    Every score maps back to triggered rules and explicit rationale.
    """

    CATEGORY_BUCKETS = {
        "document": {"Document", "Document Risks"},
        "company": {"Company", "Adverse Media", "Company Risk Indicators"},
        "country": {"Jurisdiction", "Sanctions"},
        "shipping": {"Shipping", "Commodity"},
        "financial": {"Pricing", "Payment", "Trade Finance", "Quantity"},
        "historical": {"Pattern"},
    }

    def __init__(self) -> None:
        self.cfg = get_config()
        self.weights = {
            "document": float(self.cfg.get("risk.weights.document", 0.20)),
            "company": float(self.cfg.get("risk.weights.company", 0.20)),
            "country": float(self.cfg.get("risk.weights.country", 0.15)),
            "shipping": float(self.cfg.get("risk.weights.shipping", 0.15)),
            "financial": float(self.cfg.get("risk.weights.financial", 0.15)),
            "historical": float(self.cfg.get("risk.weights.historical", 0.15)),
        }

    def assess(
        self,
        hits: list[RuleHit],
        *,
        company_score: float = 0.0,
        historical_score: float = 0.0,
        ocr_confidence: float = 100.0,
    ) -> RiskAssessment:
        buckets: dict[str, list[RuleHit]] = {k: [] for k in self.weights}
        for hit in hits:
            placed = False
            for bucket, cats in self.CATEGORY_BUCKETS.items():
                if hit.category in cats:
                    buckets[bucket].append(hit)
                    placed = True
                    break
            if not placed:
                buckets["document"].append(hit)

        factors: list[RiskFactor] = []

        doc_score = self._bucket_score(buckets["document"])
        if ocr_confidence < 70:
            doc_score = clamp(doc_score + (70 - ocr_confidence) * 0.3)
        factors.append(
            RiskFactor(
                "Document Risk",
                doc_score,
                self.weights["document"],
                self._bucket_explain("document", buckets["document"], ocr_confidence),
                [h.rule_id for h in buckets["document"]],
            )
        )

        co_score = clamp(max(self._bucket_score(buckets["company"]), company_score))
        factors.append(
            RiskFactor(
                "Company Risk",
                co_score,
                self.weights["company"],
                self._bucket_explain("company", buckets["company"])
                + (f" Company intelligence score: {company_score:.1f}." if company_score else ""),
                [h.rule_id for h in buckets["company"]],
            )
        )

        country_score = self._bucket_score(buckets["country"])
        factors.append(
            RiskFactor(
                "Country Risk",
                country_score,
                self.weights["country"],
                self._bucket_explain("country", buckets["country"]),
                [h.rule_id for h in buckets["country"]],
            )
        )

        shipping_score = self._bucket_score(buckets["shipping"])
        factors.append(
            RiskFactor(
                "Shipping Risk",
                shipping_score,
                self.weights["shipping"],
                self._bucket_explain("shipping", buckets["shipping"]),
                [h.rule_id for h in buckets["shipping"]],
            )
        )

        financial_score = self._bucket_score(buckets["financial"])
        factors.append(
            RiskFactor(
                "Financial Risk",
                financial_score,
                self.weights["financial"],
                self._bucket_explain("financial", buckets["financial"]),
                [h.rule_id for h in buckets["financial"]],
            )
        )

        hist_score = clamp(max(self._bucket_score(buckets["historical"]), historical_score))
        factors.append(
            RiskFactor(
                "Historical Similarity",
                hist_score,
                self.weights["historical"],
                self._bucket_explain("historical", buckets["historical"])
                + (
                    f" Similarity engine score: {historical_score:.1f} "
                    "(recommendation only — not an automatic classification)."
                    if historical_score
                    else ""
                ),
                [h.rule_id for h in buckets["historical"]],
            )
        )

        overall = clamp(
            sum(f.score * f.weight for f in factors) / max(sum(self.weights.values()), 1e-6)
            * (sum(self.weights.values()))  # already weighted
        )
        # Recompute cleanly
        overall = clamp(sum(f.score * f.weight for f in factors))

        level = self._level(overall)
        recommendations = self._recommendations(hits, level, factors)
        explainability = self._overall_explanation(overall, level, factors, hits)

        return RiskAssessment(
            document_risk=round(doc_score, 2),
            company_risk=round(co_score, 2),
            country_risk=round(country_score, 2),
            shipping_risk=round(shipping_score, 2),
            financial_risk=round(financial_score, 2),
            historical_similarity=round(hist_score, 2),
            overall_risk=round(overall, 2),
            level=level,
            factors=factors,
            recommendations=recommendations,
            explainability=explainability,
        )

    def _bucket_score(self, hits: list[RuleHit]) -> float:
        if not hits:
            return 0.0
        # Blend peak severity with average so a single critical hit is not washed out,
        # while multiple corroborating indicators still raise the score.
        scores = [
            SEVERITY_SCORE.get(h.severity.lower(), 50)
            * h.confidence
            * min(1.4, max(0.6, h.adjusted_weight / 6.0))
            for h in hits
        ]
        scores.sort(reverse=True)
        peak = scores[0]
        avg = sum(scores) / len(scores)
        diversity_boost = min(12.0, 2.5 * len({h.category for h in hits}))
        volume_boost = min(10.0, 1.5 * max(0, len(hits) - 1))
        return clamp(0.65 * peak + 0.35 * avg + diversity_boost + volume_boost)

    def _bucket_explain(
        self,
        name: str,
        hits: list[RuleHit],
        ocr_confidence: float | None = None,
    ) -> str:
        pretty = {
            "document": "the documents themselves",
            "company": "the companies involved",
            "country": "countries / jurisdictions",
            "shipping": "shipping and goods",
            "financial": "prices and payments",
            "historical": "earlier similar cases",
        }.get(name, name)
        if not hits:
            base = f"Nothing notable stood out about {pretty}."
        else:
            top = sorted(hits, key=lambda h: h.adjusted_weight * h.confidence, reverse=True)[:2]
            descriptions = "; ".join(h.description for h in top)
            base = f"{len(hits)} warning(s) about {pretty}. Mainly: {descriptions}."
        if ocr_confidence is not None and ocr_confidence < 70:
            base += (
                f" The scan was hard to read (about {ocr_confidence:.0f}% clear), "
                "so some details may have been missed."
            )
        return base

    def _level(self, score: float) -> str:
        low = float(self.cfg.get("risk.levels.low", 25))
        medium = float(self.cfg.get("risk.levels.medium", 50))
        high = float(self.cfg.get("risk.levels.high", 75))
        critical = float(self.cfg.get("risk.levels.critical", 90))
        if score >= critical:
            return "critical"
        if score >= high:
            return "high"
        if score >= medium:
            return "medium"
        if score >= low:
            return "low"
        return "minimal"

    def _recommendations(
        self,
        hits: list[RuleHit],
        level: str,
        factors: list[RiskFactor],
    ) -> list[str]:
        recs: list[str] = []
        if level in {"critical", "high"}:
            recs.append("Ask a senior reviewer to look at this before releasing the transaction.")
        if any(h.category == "Sanctions" for h in hits):
            recs.append("Run sanctions checks right away and hold the deal until that is cleared.")
        if any(f.name == "Company Risk" and f.score >= 50 for f in factors):
            recs.append("Dig deeper into who owns and controls the company.")
        if any(f.name == "Financial Risk" and f.score >= 50 for f in factors):
            recs.append("Double-check prices and make sure invoice, packing list, and payment amounts match.")
        if any(f.name == "Shipping Risk" and f.score >= 50 for f in factors):
            recs.append("Map the shipping route and confirm the ports make commercial sense.")
        if any(f.name == "Historical Similarity" and f.score >= 40 for f in factors):
            recs.append(
                "Compare with the similar earlier cases shown below — "
                "treat them as helpful comparisons, not automatic proof."
            )
        for h in hits[:5]:
            if h.suggested_action and h.suggested_action not in recs:
                recs.append(h.suggested_action)
        if not recs:
            recs.append("Nothing major stood out — continue with normal document checks.")
        recs.append("This tool only flags clues — a person still makes the final call.")
        return recs[:12]

    def _overall_explanation(
        self,
        overall: float,
        level: str,
        factors: list[RiskFactor],
        hits: list[RuleHit],
    ) -> str:
        level_words = {
            "critical": "very serious concerns that need immediate attention",
            "high": "significant concerns that should be reviewed carefully",
            "medium": "notable warning signs that deserve a closer look",
            "low": "a few mild warning signs",
            "minimal": "little of concern so far",
        }.get(level, "an unclear risk picture")

        lines = [
            f"Overall, this case looks like it has {level_words} (score {overall:.0f} out of 100).",
            f"{len(hits)} warning(s) contributed to this view.",
        ]
        hot = sorted(factors, key=lambda x: x.score * x.weight, reverse=True)
        for f in hot:
            if f.score < 15:
                continue
            plain_name = f.name.replace(" Risk", "").replace(
                "Historical Similarity", "Links to earlier cases"
            )
            lines.append(f"• {plain_name}: about {f.score:.0f}/100. {f.explanation}")
        if hits:
            top = sorted(hits, key=lambda h: h.adjusted_weight * h.confidence, reverse=True)[:5]
            lines.append("Most important warnings:")
            for h in top:
                lines.append(f"• {h.severity.capitalize()}: {h.description}")
        lines.append(
            "Bottom line: this is a guide for investigators — it does not decide that money laundering happened."
        )
        return "\n".join(lines)



