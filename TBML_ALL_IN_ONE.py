def extract_amounts(text: str) -> list[float]:
    """Extract monetary amounts from free text."""
    pattern = re.compile(
        r"(?:USD|EUR|GBP|AED|PKR|INR|CNY|JPY|CHF|\$|€|£)\s*([0-9]{1,3}(?:,[0-9]{3})*(?:\.[0-9]{1,2})?|"
        r"[0-9]+(?:\.[0-9]{1,2})?)|"
        r"([0-9]{1,3}(?:,[0-9]{3})*(?:\.[0-9]{1,2})?)\s*(?:USD|EUR|GBP|AED|PKR)",
        re.IGNORECASE,
    )
    results: list[float] = []
    for match in pattern.finditer(text or ""):
        raw = match.group(1) or match.group(2)
        if not raw:
            continue
        try:
            results.append(float(raw.replace(",", "")))
        except ValueError:
            continue
    return results


def is_round_amount(value: float, tolerance: float = 0.01) -> bool:
    """Detect suspiciously round invoice amounts."""
    if value <= 0:
        return False
    for base in (1000, 5000, 10000, 50000, 100000, 500000, 1000000):
        if abs(value % base) < tolerance or abs(value % base - base) < tolerance:
            if value >= base:
                return True
    return value == int(value) and value >= 10000 and value % 1000 == 0


def clamp(value: float, low: float = 0.0, high: float = 100.0) -> float:
    return max(low, min(high, value))


