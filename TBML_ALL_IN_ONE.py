class DocumentExtractor:
    """Rule-based extractor for trade document fields."""

    def extract(self, text: str, page_texts: list[str] | None = None) -> ExtractedTradeData:
        data = ExtractedTradeData()
        if not text:
            return data

        data.document_type = self._detect_doc_type(text)

        for field_name, pattern in FIELD_PATTERNS:
            match = pattern.search(text)
            if not match:
                continue
            value = match.group(1).strip() if match.lastindex else match.group(0).strip()
            value = re.sub(r"\s+", " ", value).strip(" .,:;")
            setattr(data, field_name if hasattr(data, field_name) else field_name, value)
            data.raw_fields[field_name] = value
            data.extractions.append(
                {
                    "field": field_name,
                    "value": value,
                    "matched": match.group(0)[:200],
                    "start": match.start(),
                    "end": match.end(),
                }
            )

        for field_name, pattern in PARTY_PATTERNS:
            match = pattern.search(text)
            if match:
                value = re.sub(r"\s+", " ", match.group(1)).strip(" .,:;")
                # Stop at common following labels that OCR/layout may glue on
                value = re.split(
                    r"\b(?:Address|Country|Importer|Exporter|Buyer|Seller|Description|"
                    r"Invoice|Date|HS\s*Code|Dubai|Tehran)\b",
                    value,
                    maxsplit=1,
                )[0].strip(" .,:;")
                if len(value) >= 3:
                    setattr(data, field_name, value)
                    data.raw_fields[field_name] = value
                    data.extractions.append(
                        {
                            "field": field_name,
                            "value": value,
                            "matched": match.group(0)[:200],
                            "start": match.start(),
                            "end": match.end(),
                        }
                    )

        country_match = COUNTRY_PATTERN.search(text)
        if country_match:
            data.country_origin = country_match.group(1).strip()
            data.country = data.country_origin

        # Numeric coercion
        data.quantity_value = self._to_float(data.quantity)
        data.weight_value = self._to_float(data.weight)
        data.unit_price = self._to_float(data.raw_fields.get("unit_price", ""))
        data.total_amount = self._to_float(data.raw_fields.get("total_amount", ""))

        if data.exporter:
            data.company = data.exporter
        elif data.importer:
            data.company = data.importer

        if data.port_of_discharge:
            data.destination = data.port_of_discharge

        # Description: take line after "description of goods"
        desc_match = re.search(
            r"(?:description\s+of\s+goods|goods\s+description|commodity)[:.\s]*\n?\s*([^\n]{5,200})",
            text,
            re.I,
        )
        if desc_match:
            data.description = re.sub(r"\s+", " ", desc_match.group(1)).strip()

        # Address heuristic near exporter
        addr_match = re.search(
            r"(?:address|addr)[:.\s]*([^\n]{10,120})",
            text,
            re.I,
        )
        if addr_match:
            data.address = addr_match.group(1).strip()

        logger.info(
            "Extracted %d fields from %s document",
            len(data.extractions),
            data.document_type,
        )
        return data

    def _detect_doc_type(self, text: str) -> str:
        lower = text.lower()
        best_type = "unknown"
        best_score = 0
        for doc_type, keywords in DOC_TYPE_KEYWORDS.items():
            score = sum(1 for kw in keywords if kw in lower)
            # Fuzzy boost for partial OCR errors
            for kw in keywords:
                if fuzz.partial_ratio(kw, lower[:2000]) >= 90:
                    score += 0.5
            if score > best_score:
                best_score = score
                best_type = doc_type
        return best_type if best_score > 0 else "unknown"

    @staticmethod
    def _to_float(value: str | float | None) -> float | None:
        if value is None or value == "":
            return None
        if isinstance(value, (int, float)):
            return float(value)
        try:
            return float(str(value).replace(",", "").strip())
        except ValueError:
            return None



