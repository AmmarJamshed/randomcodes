class WorkerSignals(QObject):
    """Signals emitted by background workers."""

    started = Signal()
    progress = Signal(int, str)  # percent, message
    eta = Signal(str)
    result = Signal(object)
    error = Signal(str)
    finished = Signal()
    page_done = Signal(int, int, float)  # page, total, confidence


class BaseWorker(QThread):
    """QThread worker that runs a callable without blocking the UI."""

    def __init__(
        self,
        fn: Callable[..., Any],
        *args: Any,
        parent: QObject | None = None,
        **kwargs: Any,
    ) -> None:
        super().__init__(parent)
        self.fn = fn
        self.args = args
        self.kwargs = kwargs
        self.signals = WorkerSignals()
        self._cancelled = False

    def cancel(self) -> None:
        self._cancelled = True

    @property
    def cancelled(self) -> bool:
        return self._cancelled

    def run(self) -> None:
        self.signals.started.emit()
        try:
            # Inject progress callback if the target accepts it
            kwargs = dict(self.kwargs)
            if "progress_callback" not in kwargs:
                kwargs["progress_callback"] = self._emit_progress
            if "is_cancelled" not in kwargs:
                kwargs["is_cancelled"] = lambda: self._cancelled
            result = self.fn(*self.args, **kwargs)
            if not self._cancelled:
                self.signals.result.emit(result)
        except TypeError:
            # Callable may not accept progress_callback
            try:
                result = self.fn(*self.args, **self.kwargs)
                if not self._cancelled:
                    self.signals.result.emit(result)
            except Exception as exc:  # noqa: BLE001
                logger.error("Worker failed: %s\n%s", exc, traceback.format_exc())
                self.signals.error.emit(str(exc))
        except Exception as exc:  # noqa: BLE001
            logger.error("Worker failed: %s\n%s", exc, traceback.format_exc())
            self.signals.error.emit(str(exc))
        finally:
            self.signals.finished.emit()

    def _emit_progress(self, percent: int, message: str, eta: str | None = None) -> None:
        self.signals.progress.emit(int(percent), message)
        if eta:
            self.signals.eta.emit(eta)


class TaskQueue:
    """Named thread-pool queues for OCR, search, and rule evaluation."""

    def __init__(self, max_workers: int = 4) -> None:
        self._pools: dict[str, ThreadPoolExecutor] = {
            "ocr": ThreadPoolExecutor(max_workers=max_workers, thread_name_prefix="ocr"),
            "search": ThreadPoolExecutor(max_workers=3, thread_name_prefix="search"),
            "rules": ThreadPoolExecutor(max_workers=2, thread_name_prefix="rules"),
            "general": ThreadPoolExecutor(max_workers=4, thread_name_prefix="general"),
        }

    def submit(self, queue: str, fn: Callable[..., Any], *args: Any, **kwargs: Any):
        pool = self._pools.get(queue) or self._pools["general"]
        return pool.submit(fn, *args, **kwargs)

    def shutdown(self, wait: bool = True) -> None:
        for pool in self._pools.values():
            pool.shutdown(wait=wait, cancel_futures=not wait)


_task_queue: TaskQueue | None = None


def get_task_queue() -> TaskQueue:
    global _task_queue
    if _task_queue is None:
        from config import get_config

        workers = int(get_config().get("ocr.max_workers", 4))
        _task_queue = TaskQueue(max_workers=workers)
    return _task_queue



