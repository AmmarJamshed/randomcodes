def _verdict(score: float, classification: ClassificationResult) -> str:
    neg_codes = {f.code for f in classification.negative}
    if score >= 70 or "negative_news" in neg_codes or "shell_indicators" in neg_codes:
        return "high_concern"
    if score >= 45 or "no_registry" in neg_codes or "new_domain" in neg_codes:
        return "needs_caution"
    if score <= 25 and any(f.code in {"verified_registration", "official_website", "long_history"} for f in classification.positive):
        return "looks_established"
    return "inconclusive"


VERDICT_LABELS = {
    "looks_established": "Looks established",
    "needs_caution": "Needs caution",
    "high_concern": "High concern",
    "inconclusive": "Inconclusive — more checks needed",
}


def _plain_summary(name: str, role: str, intel: dict[str, Any], clf: ClassificationResult) -> str:
    verdict = VERDICT_LABELS[_verdict(clf.score, clf)]
    parts = [
        f"Automatic check for {role}: {name}.",
        f"Verdict: {verdict} (company caution score {clf.score:.0f}/100).",
    ]
    if intel.get("website"):
        parts.append(f"Website found: {intel['website']}.")
    else:
        parts.append("No clear official website was found.")
    regs = intel.get("registry_hits") or intel.get("opencorporates") or []
    active = [r for r in regs if isinstance(r, dict) and not r.get("error")]
    if active:
        first = active[0]
        status = first.get("current_status") or "unknown status"
        parts.append(
            f"Public registry hit: {first.get('name', name)} "
            f"({first.get('jurisdiction_code', '')}, {status})."
        )
    else:
        parts.append("No clear public company registration was located.")
    if intel.get("domain_age_days") is not None:
        parts.append(f"Domain age about {intel['domain_age_days']} days.")
    pos = [f.label for f in clf.positive[:4]]
    neg = [f.label for f in clf.negative[:5]]
    if pos:
        parts.append("Encouraging signs: " + "; ".join(pos) + ".")
    if neg:
        parts.append("Worrying signs: " + "; ".join(neg) + ".")
    return " ".join(parts)


def collect_parties(extracted: ExtractedTradeData) -> list[dict[str, str]]:
    """Deduplicate exporter / importer / company names from extraction."""
    parties: list[dict[str, str]] = []
    seen: set[str] = set()

    candidates = [
        ("exporter", extracted.exporter, extracted.country_origin or extracted.country),
        ("importer", extracted.importer, extracted.country_destination or extracted.country),
        ("company", extracted.company, extracted.country),
        ("bank", extracted.bank, ""),
    ]
    for role, name, country in candidates:
        clean = (name or "").strip()
        if len(clean) < 3:
            continue
        # Skip banks from auto web verification by default — still listable but noisy
        if role == "bank":
            continue
        key = normalize_text(clean)
        if key in seen:
            continue
        # Avoid near-duplicates (same firm listed as exporter and company)
        if any(key in s or s in key for s in seen if len(s) > 5):
            continue
        seen.add(key)
        parties.append({"name": clean, "role": role, "country": (country or "").strip()})
    return parties


def merge_classifications(results: list[ClassificationResult]) -> ClassificationResult:
    if not results:
        return ClassificationResult(explanation="No companies were verified.")
    pos: list[Finding] = []
    neg: list[Finding] = []
    seen_pos: set[str] = set()
    seen_neg: set[str] = set()
    for clf in results:
        for f in clf.positive:
            if f.code not in seen_pos:
                pos.append(f)
                seen_pos.add(f.code)
        for f in clf.negative:
            if f.code not in seen_neg:
                neg.append(f)
                seen_neg.add(f.code)
    score = max(c.score for c in results)
    return ClassificationResult(
        positive=pos,
        negative=neg,
        score=round(score, 2),
        explanation=(
            f"Merged automatic checks across {len(results)} entit(y/ies). "
            f"Highest company caution score={score:.1f}/100."
        ),
    )


