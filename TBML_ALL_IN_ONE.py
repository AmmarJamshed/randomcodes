class ImageEnhancer:
    """OpenCV preprocessing: deskew, denoise, threshold, sharpen."""

    def __init__(self, cfg: dict[str, Any] | None = None) -> None:
        app = get_config()
        self.deskew = bool(app.get("ocr.deskew", True))
        self.denoise = bool(app.get("ocr.denoise", True))
        self.adaptive = bool(app.get("ocr.adaptive_threshold", True))
        self.sharpen = bool(app.get("ocr.sharpen", True))

    def enhance(self, image: np.ndarray) -> tuple[np.ndarray, int]:
        rotation = 0
        if len(image.shape) == 3:
            gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
        else:
            gray = image.copy()

        if self.deskew:
            gray, rotation = self._deskew(gray)

        if self.denoise:
            gray = cv2.fastNlMeansDenoising(gray, None, 10, 7, 21)

        if self.adaptive:
            gray = cv2.adaptiveThreshold(
                gray, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C, cv2.THRESH_BINARY, 31, 11
            )
        else:
            _, gray = cv2.threshold(gray, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)

        if self.sharpen:
            kernel = np.array([[0, -1, 0], [-1, 5, -1], [0, -1, 0]], dtype=np.float32)
            gray = cv2.filter2D(gray, -1, kernel)

        return gray, rotation

    def _deskew(self, gray: np.ndarray) -> tuple[np.ndarray, int]:
        try:
            coords = np.column_stack(np.where(gray < 200))
            if coords.size == 0:
                return gray, 0
            angle = cv2.minAreaRect(coords)[-1]
            if angle < -45:
                angle = -(90 + angle)
            else:
                angle = -angle
            if abs(angle) < 0.5 or abs(angle) > 15:
                # Try OSD-style coarse rotation later; skip tiny/huge skews here
                if abs(angle) < 0.5:
                    return gray, 0
            h, w = gray.shape[:2]
            matrix = cv2.getRotationMatrix2D((w // 2, h // 2), angle, 1.0)
            rotated = cv2.warpAffine(
                gray, matrix, (w, h), flags=cv2.INTER_CUBIC, borderMode=cv2.BORDER_REPLICATE
            )
            return rotated, int(round(angle))
        except Exception:  # noqa: BLE001
            return gray, 0

    @staticmethod
    def is_blank(gray: np.ndarray, threshold: float = 0.02) -> bool:
        """Heuristic blank-page detection based on ink ratio."""
        ink = np.mean(gray < 128)
        return float(ink) < threshold


class OCREngine:
    """Tesseract OCR wrapper with bundled-tool autodetection."""

    def __init__(self) -> None:
        self.locations = set_env_from_tools()
        self.cfg = get_config()
        self._configure_tesseract()

    def _configure_tesseract(self) -> None:
        import pytesseract

        cmd = self.locations.get("tesseract") or __import__("os").environ.get("TBML_TESSERACT_CMD")
        if cmd:
            pytesseract.pytesseract.tesseract_cmd = cmd
        tessdata = self.locations.get("tessdata")
        if tessdata:
            self._tessdata_config = f'--tessdata-dir "{tessdata}"'
        else:
            self._tessdata_config = ""

    def ocr_image(self, image: np.ndarray, lang: str | None = None) -> PageOCRResult:
        import pytesseract
        from pytesseract import Output

        lang = lang or str(self.cfg.get("ocr.language", "eng"))
        config = f"{self._tessdata_config} --oem 3 --psm 3".strip()

        pil = Image.fromarray(image)
        data = pytesseract.image_to_data(pil, lang=lang, config=config, output_type=Output.DICT)
        text = pytesseract.image_to_string(pil, lang=lang, config=config)

        confidences: list[float] = []
        words: list[dict[str, Any]] = []
        n = len(data.get("text", []))
        for i in range(n):
            word = (data["text"][i] or "").strip()
            conf = float(data["conf"][i])
            if not word or conf < 0:
                continue
            confidences.append(conf)
            words.append(
                {
                    "text": word,
                    "confidence": conf,
                    "left": int(data["left"][i]),
                    "top": int(data["top"][i]),
                    "width": int(data["width"][i]),
                    "height": int(data["height"][i]),
                    "page_num": int(data.get("page_num", [1])[i] if data.get("page_num") else 1),
                }
            )

        avg_conf = sum(confidences) / len(confidences) if confidences else 0.0
        h, w = image.shape[:2]
        return PageOCRResult(
            page_number=0,
            text=text.strip(),
            confidence=round(avg_conf, 2),
            width=w,
            height=h,
            words=words,
        )


class DocumentOCRPipeline:
    """
    Full offline OCR pipeline with SHA-256 caching and live progress.
    Supports PDF, DOCX (text extract), and image formats.
    """

    SUPPORTED = {".pdf", ".docx", ".png", ".jpg", ".jpeg", ".bmp", ".tiff", ".tif"}

    def __init__(self) -> None:
        self.cfg = get_config()
        self.locations = set_env_from_tools()
        self.enhancer = ImageEnhancer()
        self.engine = OCREngine()
        self.cache_dir = self.cfg.resolve_path("cache_ocr")
        self.cache_dir.mkdir(parents=True, exist_ok=True)
        self.dpi = int(self.cfg.get("ocr.dpi", 300))
        self.conf_threshold = float(self.cfg.get("ocr.confidence_threshold", 70.0))
        self.blank_threshold = float(self.cfg.get("ocr.blank_page_threshold", 0.02))

    def process(
        self,
        file_path: str | Path,
        *,
        progress_callback: ProgressCallback | None = None,
        is_cancelled: Callable[[], bool] | None = None,
        force: bool = False,
        pages: list[int] | None = None,
    ) -> DocumentOCRResult:
        path = Path(file_path)
        if not path.exists():
            raise FileNotFoundError(f"Document not found: {path}")
        if path.suffix.lower() not in self.SUPPORTED:
            raise ValueError(f"Unsupported file type: {path.suffix}")

        start = time.time()
        file_hash = sha256_file(path)

        def report(pct: int, msg: str, eta: str | None = None) -> None:
            if progress_callback:
                progress_callback(pct, msg, eta)

        # Cache lookup
        cache_file = self.cache_dir / f"{file_hash}.json"
        if cache_file.exists() and not force:
            report(100, "Loaded from OCR cache", "0s")
            data = json.loads(cache_file.read_text(encoding="utf-8"))
            pages_out = [PageOCRResult(**p) for p in data["pages"]]
            return DocumentOCRResult(
                file_path=str(path),
                file_hash=file_hash,
                page_count=data["page_count"],
                pages=pages_out,
                full_text=data["full_text"],
                average_confidence=data["average_confidence"],
                low_confidence_pages=data["low_confidence_pages"],
                cached=True,
                elapsed_seconds=round(time.time() - start, 2),
            )

        suffix = path.suffix.lower()
        report(2, "Loading document", None)

        if suffix == ".docx":
            result = self._process_docx(path, file_hash, report)
        elif suffix == ".pdf":
            result = self._process_pdf(path, file_hash, report, is_cancelled, pages)
        else:
            result = self._process_image(path, file_hash, report)

        result.elapsed_seconds = round(time.time() - start, 2)

        # Persist cache
        try:
            cache_file.write_text(
                json.dumps(result.to_dict(), ensure_ascii=False),
                encoding="utf-8",
            )
        except Exception as exc:  # noqa: BLE001
            logger.warning("Failed to write OCR cache: %s", exc)

        report(100, "OCR complete", "0s")
        return result

    def retry_page(
        self,
        file_path: str | Path,
        page_number: int,
        *,
        progress_callback: ProgressCallback | None = None,
    ) -> PageOCRResult:
        """Re-run OCR on a single page and update cache."""
        result = self.process(
            file_path,
            progress_callback=progress_callback,
            force=True,
            pages=[page_number],
        )
        for page in result.pages:
            if page.page_number == page_number:
                return page
        raise ValueError(f"Page {page_number} not found after retry")

    def _process_docx(
        self,
        path: Path,
        file_hash: str,
        report: ProgressCallback,
    ) -> DocumentOCRResult:
        from docx import Document as DocxDocument

        report(20, "Extracting DOCX text", None)
        doc = DocxDocument(str(path))
        paragraphs = [p.text for p in doc.paragraphs if p.text.strip()]
        for table in doc.tables:
            for row in table.rows:
                cells = [c.text.strip() for c in row.cells if c.text.strip()]
                if cells:
                    paragraphs.append(" | ".join(cells))
        text = "\n".join(paragraphs)
        page = PageOCRResult(
            page_number=1,
            text=text,
            confidence=100.0,
            width=0,
            height=0,
            words=[],
        )
        report(90, "DOCX extraction complete", None)
        return DocumentOCRResult(
            file_path=str(path),
            file_hash=file_hash,
            page_count=1,
            pages=[page],
            full_text=text,
            average_confidence=100.0,
            low_confidence_pages=[],
        )

    def _process_image(
        self,
        path: Path,
        file_hash: str,
        report: ProgressCallback,
    ) -> DocumentOCRResult:
        report(10, "Loading image", None)
        image = cv2.imread(str(path))
        if image is None:
            # Pillow fallback for TIFF etc.
            pil = Image.open(path).convert("RGB")
            image = cv2.cvtColor(np.array(pil), cv2.COLOR_RGB2BGR)

        report(40, "Enhancing image", None)
        enhanced, rotation = self.enhancer.enhance(image)
        is_blank = self.enhancer.is_blank(enhanced, self.blank_threshold)

        report(70, "Running OCR", None)
        if is_blank:
            page = PageOCRResult(
                page_number=1,
                text="",
                confidence=0.0,
                width=enhanced.shape[1],
                height=enhanced.shape[0],
                is_blank=True,
                rotation=rotation,
            )
        else:
            page = self.engine.ocr_image(enhanced)
            page.page_number = 1
            page.rotation = rotation

        # Save preview
        preview_dir = self.cache_dir / file_hash
        preview_dir.mkdir(parents=True, exist_ok=True)
        preview_path = preview_dir / "page_001.png"
        cv2.imwrite(str(preview_path), enhanced)
        page.image_path = str(preview_path)

        low = [1] if page.confidence < self.conf_threshold and not page.is_blank else []
        return DocumentOCRResult(
            file_path=str(path),
            file_hash=file_hash,
            page_count=1,
            pages=[page],
            full_text=page.text,
            average_confidence=page.confidence,
            low_confidence_pages=low,
        )

    def _process_pdf(
        self,
        path: Path,
        file_hash: str,
        report: ProgressCallback,
        is_cancelled: Callable[[], bool] | None,
        pages_filter: list[int] | None,
    ) -> DocumentOCRResult:
        report(5, "Loading PDF", None)

        # Fast path: extract embedded text from digital PDFs (no OCR needed)
        text_result = self._pdf_text_layer(path, file_hash, report, pages_filter)
        if text_result is not None:
            return text_result

        # Prefer PyMuPDF for rendering (no Poppler required); fall back to pdf2image
        images = self._pdf_to_images(path, report)
        total = len(images)
        if total == 0:
            raise RuntimeError("PDF produced zero pages")

        if pages_filter:
            selected = [(i, img) for i, img in enumerate(images, start=1) if i in pages_filter]
        else:
            selected = list(enumerate(images, start=1))

        report(15, f"Converting Pages (0 / {len(selected)})", None)

        preview_dir = self.cache_dir / file_hash
        preview_dir.mkdir(parents=True, exist_ok=True)

        page_results: list[PageOCRResult] = []
        page_start = time.time()

        for idx, (page_num, image) in enumerate(selected, start=1):
            if is_cancelled and is_cancelled():
                raise RuntimeError("OCR cancelled by user")

            elapsed = time.time() - page_start
            avg = elapsed / max(idx - 1, 1) if idx > 1 else 8.0
            remaining = avg * (len(selected) - idx + 1)
            eta = self._format_eta(remaining)

            report(
                15 + int(75 * (idx - 1) / len(selected)),
                f"Enhancing Images — page {page_num}",
                eta,
            )
            enhanced, rotation = self.enhancer.enhance(image)
            is_blank = (
                bool(self.cfg.get("ocr.skip_blank_pages", True))
                and self.enhancer.is_blank(enhanced, self.blank_threshold)
            )

            report(
                15 + int(75 * (idx - 0.5) / len(selected)),
                f"OCR Page {page_num} / {total}",
                eta,
            )

            if is_blank:
                page = PageOCRResult(
                    page_number=page_num,
                    text="",
                    confidence=0.0,
                    width=enhanced.shape[1],
                    height=enhanced.shape[0],
                    is_blank=True,
                    rotation=rotation,
                )
            else:
                page = self.engine.ocr_image(enhanced)
                page.page_number = page_num
                page.rotation = rotation

            preview_path = preview_dir / f"page_{page_num:03d}.png"
            cv2.imwrite(str(preview_path), enhanced)
            page.image_path = str(preview_path)
            page_results.append(page)

        report(92, "Extracting Tables", None)

        full_text = "\n\n".join(
            f"--- Page {p.page_number} ---\n{p.text}" for p in page_results if p.text
        )
        confs = [p.confidence for p in page_results if not p.is_blank]
        avg_conf = sum(confs) / len(confs) if confs else 0.0
        low = [
            p.page_number
            for p in page_results
            if not p.is_blank and p.confidence < self.conf_threshold
        ]

        return DocumentOCRResult(
            file_path=str(path),
            file_hash=file_hash,
            page_count=total,
            pages=page_results,
            full_text=full_text,
            average_confidence=round(avg_conf, 2),
            low_confidence_pages=low,
        )

    def _pdf_text_layer(
        self,
        path: Path,
        file_hash: str,
        report: ProgressCallback,
        pages_filter: list[int] | None,
    ) -> DocumentOCRResult | None:
        """Use embedded PDF text when pages are digital (not scanned)."""
        try:
            import fitz
        except Exception:
            return None

        try:
            doc = fitz.open(str(path))
        except Exception as exc:  # noqa: BLE001
            logger.warning("Could not open PDF for text layer: %s", exc)
            return None

        page_results: list[PageOCRResult] = []
        preview_dir = self.cache_dir / file_hash
        preview_dir.mkdir(parents=True, exist_ok=True)
        usable_chars = 0

        try:
            for i, page in enumerate(doc, start=1):
                if pages_filter and i not in pages_filter:
                    continue
                report(10 + int(40 * i / max(len(doc), 1)), f"Reading PDF text — page {i}", None)
                text = (page.get_text("text") or "").strip()
                usable_chars += len(text.replace(" ", "").replace("\n", ""))

                # Render a preview image for the viewer
                zoom = min(2.0, self.dpi / 72.0)
                pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
                preview_path = preview_dir / f"page_{i:03d}.png"
                pix.save(str(preview_path))

                page_results.append(
                    PageOCRResult(
                        page_number=i,
                        text=text,
                        confidence=100.0 if len(text) > 20 else 0.0,
                        width=int(pix.width),
                        height=int(pix.height),
                        words=[],
                        is_blank=len(text) < 5,
                        image_path=str(preview_path),
                    )
                )
        finally:
            doc.close()

        # Heuristic: if almost no extractable text, fall back to OCR
        if usable_chars < 80:
            report(12, "PDF looks scanned — switching to OCR", None)
            return None

        report(90, "Digital PDF text extracted", None)
        full_text = "\n\n".join(
            f"--- Page {p.page_number} ---\n{p.text}" for p in page_results if p.text
        )
        return DocumentOCRResult(
            file_path=str(path),
            file_hash=file_hash,
            page_count=len(page_results),
            pages=page_results,
            full_text=full_text,
            average_confidence=100.0,
            low_confidence_pages=[],
        )

    def _pdf_to_images(
        self,
        path: Path,
        report: ProgressCallback,
    ) -> list[np.ndarray]:
        """Render PDF pages to images using PyMuPDF, then Poppler fallback."""
        images: list[np.ndarray] = []

        try:
            import fitz  # PyMuPDF

            doc = fitz.open(str(path))
            zoom = self.dpi / 72.0
            matrix = fitz.Matrix(zoom, zoom)
            for i, page in enumerate(doc):
                report(8 + int(6 * i / max(len(doc), 1)), f"Converting Pages ({i + 1} / {len(doc)})", None)
                pix = page.get_pixmap(matrix=matrix, alpha=False)
                img = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width, 3)
                img = cv2.cvtColor(img, cv2.COLOR_RGB2BGR)
                images.append(img)
            doc.close()
            if images:
                return images
        except Exception as exc:  # noqa: BLE001
            logger.warning("PyMuPDF render failed, trying pdf2image: %s", exc)

        try:
            from pdf2image import convert_from_path

            poppler_path = self.locations.get("poppler")
            kwargs: dict[str, Any] = {"dpi": self.dpi}
            if poppler_path:
                kwargs["poppler_path"] = poppler_path
            pil_pages = convert_from_path(str(path), **kwargs)
            for pil in pil_pages:
                images.append(cv2.cvtColor(np.array(pil.convert("RGB")), cv2.COLOR_RGB2BGR))
            return images
        except Exception as exc:  # noqa: BLE001
            raise RuntimeError(
                "Unable to convert PDF. Bundle Poppler under tools/poppler or ensure PyMuPDF works. "
                f"Details: {exc}"
            ) from exc

    @staticmethod
    def _format_eta(seconds: float) -> str:
        seconds = max(0, int(seconds))
        if seconds < 60:
            return f"{seconds}s"
        mins, secs = divmod(seconds, 60)
        if mins < 60:
            return f"{mins}m {secs}s"
        hours, mins = divmod(mins, 60)
        return f"{hours}h {mins}m"



