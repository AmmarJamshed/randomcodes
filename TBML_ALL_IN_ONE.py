class BasePlugin(ABC):
    """
    Base class for optional investigation modules.

    Future plugins may include:
      CDD, KYC, PEP Screening, Sanctions Screening, Adverse Media,
      Invoice Fraud, Document Forgery Detection, Beneficial Ownership,
      Relationship Mapping, SAR Drafting, Customer Risk Rating.
    """

    id: str = "base"
    name: str = "Base Plugin"
    version: str = "1.0.0"
    description: str = ""
    enabled: bool = True

    def initialize(self, context: PluginContext) -> None:
        self.context = context

    @abstractmethod
    def run(self, payload: dict[str, Any]) -> dict[str, Any]:
        """Execute plugin logic and return a JSON-serialisable result dict."""

    def shutdown(self) -> None:
        return None


class PluginManager:
    """Discover, register, and execute plugins from modules/plugins."""

    def __init__(self) -> None:
        self._plugins: dict[str, BasePlugin] = {}
        self.context = PluginContext()

    def register(self, plugin: BasePlugin) -> None:
        if not plugin.enabled:
            return
        plugin.initialize(self.context)
        self._plugins[plugin.id] = plugin
        logger.info("Registered plugin: %s (%s)", plugin.id, plugin.name)

    def discover(self, package_name: str = "modules.plugins") -> None:
        try:
            package = importlib.import_module(package_name)
        except ImportError:
            logger.warning("Plugin package %s not found", package_name)
            return
        if not hasattr(package, "__path__"):
            return
        for modinfo in pkgutil.iter_modules(package.__path__, package.__name__ + "."):
            if modinfo.name.endswith(".base"):
                continue
            try:
                module = importlib.import_module(modinfo.name)
                for attr_name in dir(module):
                    attr = getattr(module, attr_name)
                    if (
                        isinstance(attr, type)
                        and issubclass(attr, BasePlugin)
                        and attr is not BasePlugin
                    ):
                        self.register(attr())
            except Exception as exc:  # noqa: BLE001
                logger.error("Failed loading plugin module %s: %s", modinfo.name, exc)

    def list_plugins(self) -> list[dict[str, str]]:
        return [
            {
                "id": p.id,
                "name": p.name,
                "version": p.version,
                "description": p.description,
            }
            for p in self._plugins.values()
        ]

    def run(self, plugin_id: str, payload: dict[str, Any]) -> dict[str, Any]:
        plugin = self._plugins.get(plugin_id)
        if not plugin:
            raise KeyError(f"Plugin not found: {plugin_id}")
        return plugin.run(payload)

    def run_all(self, payload: dict[str, Any]) -> dict[str, Any]:
        results = {}
        for pid, plugin in self._plugins.items():
            try:
                results[pid] = plugin.run(payload)
            except Exception as exc:  # noqa: BLE001
                logger.error("Plugin %s failed: %s", pid, exc)
                results[pid] = {"error": str(exc)}
        return results


