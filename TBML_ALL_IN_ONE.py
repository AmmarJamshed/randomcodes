class DarkButton(tk.Frame):
    """Simple flat button matching the dark theme."""

    def __init__(
        self,
        master: tk.Misc,
        text: str,
        command: Any = None,
        *,
        primary: bool = False,
        nav: bool = False,
        width: int = 0,
    ) -> None:
        super().__init__(master, bg=NAV_BG if nav else CARD_BG)
        self._command = command
        self._nav = nav
        self._primary = primary
        self._active = False
        bg = ACCENT if primary else (NAV_BG if nav else BTN_BG)
        fg = "#082f49" if primary else TEXT
        self.btn = tk.Label(
            self,
            text=text,
            bg=bg,
            fg=fg,
            font=("Segoe UI", 10, "bold" if primary or nav else "normal"),
            padx=14,
            pady=10,
            cursor="hand2",
            anchor="w" if nav else "center",
        )
        if width:
            self.btn.configure(width=width)
        self.btn.pack(fill=tk.X)
        self.btn.bind("<Button-1>", self._click)
        self.btn.bind("<Enter>", self._enter)
        self.btn.bind("<Leave>", self._leave)

    def _click(self, _e: object = None) -> None:
        if self._command:
            self._command()

    def _enter(self, _e: object = None) -> None:
        if self._active:
            return
        if self._primary:
            self.btn.configure(bg=ACCENT_HI)
        elif self._nav:
            self.btn.configure(bg=BTN_BG)
        else:
            self.btn.configure(bg=BTN_BORDER)

    def _leave(self, _e: object = None) -> None:
        if self._active:
            return
        if self._primary:
            self.btn.configure(bg=ACCENT, fg="#082f49")
        elif self._nav:
            self.btn.configure(bg=NAV_BG, fg=TEXT)
        else:
            self.btn.configure(bg=BTN_BG, fg=TEXT)

    def set_active(self, active: bool) -> None:
        self._active = active
        if not self._nav:
            return
        if active:
            self.btn.configure(bg=ACCENT, fg="#082f49", font=("Segoe UI", 10, "bold"))
        else:
            self.btn.configure(bg=NAV_BG, fg="#cbd5e1", font=("Segoe UI", 10))


